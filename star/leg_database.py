"""Section 3.1 Leg Database builder for ballistic Lambert legs.

A "leg" is one heliocentric arc connecting two consecutive encounter nodes
(departure body at stage i → arrival body at stage i+1).  Each leg row stores
the two v-infinity vectors (departure and arrival) needed to patch into the
surrounding flyby/DSM maneuvers.

Index glossary
--------------
IL  : Leg index   — sequential integer assigned to each leg row within one stage (0-based).
ID  : Departure encounter index (IE) — points into EncounterDB for the departure node.
IA  : Arrival encounter index (IE)   — points into EncounterDB for the arrival node.
tof : Time of flight — elapsed time from departure to arrival [seconds].
vinf: v-infinity     — spacecraft velocity relative to the body at encounter [km/s].
dv  : Delta-v        — impulsive velocity change, here from a DSM maneuver [km/s].
eta : DSM split fraction — fraction of tof at which the DSM is placed (0 = departure, 1 = arrival).

See NOTATION.md for the full glossary (stage kinds, lev_type sign pairs,
lambert_hz, and the IL-is-stage-scoped caveat).

What `LegDatabase` stores:
  `IL`, `ID`, `IA` integer arrays plus `vinfD_km_s`, `vinfA_km_s` as `(N,3)`
  float arrays, along with per-row signed `n_rev`, DSM leveraging magnitude
  `dv_lev_km_s`, and DSM split fraction `eta_lev`.

Deterministic ordering:
  Candidates are generated by departure entries sorted by `(t_et, IE)` and, for each
  departure, arrivals sorted by `(t_et, IE)`. `IL` is assigned sequentially from 0.

Filters:
  1) time-of-flight filter keeps only `dt_s > dt_positive_tol_s` and
     `tof_min_s <= dt_s <= tof_max_s` (with `+/-inf` treated as unbounded),
  2) `v_infinity` filter keeps only rows whose `||vinfD||` and `||vinfA||` are inside
     configured `[min,max]` bounds,
  3) Lambert failures are skipped.

Current coverage of leg types:
    - lambert
    - resonant
    - DSM (leveraging) with solve_arc objective types
    - null leg

NOT implemented yet:
    - rendezvous leg
"""

